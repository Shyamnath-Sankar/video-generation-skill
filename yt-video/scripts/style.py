#!/usr/bin/env python3
"""Apply a style preset to a Short project: writes style.css (fonts + CSS variables) and style.js (window.STYLE).

usage: style.py <project_dir> <style_name | path/to/style.json>
       style.py --list

The project page loads style.css and style.js, and kit.js reads window.STYLE for the palette,
caption look, scene transition, background and motion defaults. Edit the project's style.json
copy and re-run to tweak a preset for one video.
"""
import json, pathlib, shutil, sys

SKILL = pathlib.Path(__file__).resolve().parent.parent
STYLES = SKILL / "styles"
FONTS = SKILL / "assets" / "fonts"

# family -> [(file, weight range, style)]; every file is OFL or MIT (see assets/fonts/LICENSES.md)
FONT_REGISTRY = {
    "Geist": [("Geist-Variable.woff2", "100 900", "normal")],
    "Geist Mono": [("GeistMono-Medium.woff2", "100 900", "normal")],
    "KaTeX_Main": [("KaTeX_Main-Regular.woff2", "400", "normal"), ("KaTeX_Main-Italic.woff2", "400", "italic"),
                   ("KaTeX_Main-Bold.woff2", "700", "normal")],
    "KaTeX_Math": [("KaTeX_Math-Italic.woff2", "400", "normal")],
    "Nunito": [("Nunito-Variable.woff2", "200 1000", "normal")],
    "Playfair Display": [("PlayfairDisplay-400.woff2", "400", "normal"), ("PlayfairDisplay-400-Italic.woff2", "400", "italic"),
                         ("PlayfairDisplay-800.woff2", "800", "normal")],
    "Anton": [("Anton-Regular.woff2", "400", "normal")],
    "JetBrains Mono": [("JetBrainsMono-500.woff2", "500", "normal"), ("JetBrainsMono-700.woff2", "700", "normal")],
}
FALLBACK = {"mono": "ui-monospace, monospace", "math": "serif"}


def load_style(name_or_path):
    p = pathlib.Path(name_or_path)
    if p.suffix == ".json" and p.exists():
        return json.loads(p.read_text())
    f = STYLES / name_or_path / "style.json"
    if not f.exists():
        raise SystemExit(f"unknown style '{name_or_path}'. Available: {', '.join(list_styles())}")
    return json.loads(f.read_text())


def list_styles():
    return sorted(d.name for d in STYLES.iterdir() if (d / "style.json").exists())


def apply(project, style):
    project = pathlib.Path(project)
    fdir = project / "assets" / "fonts"
    fdir.mkdir(parents=True, exist_ok=True)
    families = {}
    for role, fam in style.get("fonts", {}).items():
        if fam not in FONT_REGISTRY:
            raise SystemExit(f"font '{fam}' ({role}) is not in the registry: {', '.join(FONT_REGISTRY)}. "
                             "Add the woff2 to assets/fonts and to FONT_REGISTRY in scripts/style.py.")
        families[fam] = FONT_REGISTRY[fam]
    css = []
    for fam, files in families.items():
        for file, weight, fstyle in files:
            shutil.copy2(FONTS / file, fdir / file)
            css.append(f"@font-face{{font-family:'{fam}';src:url(assets/fonts/{file}) format('woff2');"
                       f"font-weight:{weight};font-style:{fstyle};font-display:block}}")
    for lic in FONTS.glob("*.txt"):
        shutil.copy2(lic, fdir / lic.name)
    if (FONTS / "LICENSES.md").exists():
        shutil.copy2(FONTS / "LICENSES.md", fdir / "LICENSES.md")
    c, f, w, cap = style.get("colors", {}), style.get("fonts", {}), style.get("weights", {}), style.get("captions", {})
    var = [f"--{k}:{v}" for k, v in c.items()]
    for role, fam in f.items():
        var.append(f"--font-{role}:'{fam}', {FALLBACK.get(role, 'system-ui, sans-serif')}")
    var.append(f"--w-display:{w.get('display', 800)}")
    var.append(f"--w-body:{w.get('body', 500)}")
    cap_font = f.get(cap.get("font", "display"), f.get("display", "Geist"))
    var.append(f"--cap-font:'{cap_font}', system-ui, sans-serif")
    var.append(f"--cap-stroke:{c.get(cap.get('stroke', 'bg'), cap.get('stroke', '#000'))}")
    var.append(f"--cap-stroke-w:{cap.get('strokeWidth', 0)}px")
    css.append(":root{" + ";".join(var) + "}")
    (project / "style.css").write_text("/* generated by scripts/style.py from style.json; edit style.json and re-run */\n" + "\n".join(css) + "\n")
    (project / "style.js").write_text("/* generated by scripts/style.py */\nwindow.STYLE = " + json.dumps(style, indent=1) + ";\n")
    (project / "style.json").write_text(json.dumps(style, indent=2) + "\n")
    return style


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--list":
        for n in list_styles():
            s = load_style(n)
            print(f"{n:20s} {s.get('label', '')}")
        sys.exit(0)
    if len(sys.argv) != 3:
        print(__doc__); sys.exit(2)
    s = apply(sys.argv[1], load_style(sys.argv[2]))
    print(f"style '{s['name']}' applied to {sys.argv[1]} (style.css, style.js, style.json)")
